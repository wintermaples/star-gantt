#!/usr/bin/env node
// tools/gen-render-order.mjs
//
// See docs/specs/architecture.md chapter 7 ("z-order table
// generation"): once the order-key registry (`ctx.claimOrder`, architecture.md chapter 1.2) has
// real registrants, this script starts a headless host, loads the official plugin set, reads
// `host.orders("renderer/layers")` (architecture.md §1.2 — a snapshot array of every registration
// in a scope, `{ key, order, pluginId }`, sorted ascending by `order`) and regenerates
// docs/specs/render-order.md as a Markdown table from that live registry data — replacing a
// hand-written z-order table with a generated artifact reviewed via commit diff.
//
// Usage: `node tools/gen-render-order.mjs` (run from anywhere; paths below are resolved relative
// to this file). Targets the *built* `dist/` of `@stargantt/core` and `@stargantt/preset-standard`
// — like the E2E suite (e2e/README.md), this reads compiled output, not source, so run
// `pnpm run build` first or the table reflects a stale composition.
//
// Headless host: `@stargantt/core` only ever touches `element` as an `HTMLElement`-typed value
// except where the view plugin does real DOM work (canvases, ResizeObserver, panes), so this
// script boots a happy-dom `Window` and copies its globals onto `globalThis` (skipping `console`,
// so real stdout/stderr are kept) rather than using `sdk/testing`'s `createTestHost`, which falls
// back to a *headless* (non-DOM) element when none is given — the view plugin's `setup()` needs a
// real `document` to create its panes and canvases. happy-dom ships no canvas rendering backend,
// so `HTMLCanvasElement.prototype.getContext("2d")` is monkey-patched to a no-op proxy: this
// script never reads pixels, only registrations made during `setup()`.

import { writeFile } from "node:fs/promises";
import { Window } from "happy-dom";

const CORE_DIST = new URL("../packages/core/dist/core.js", import.meta.url);
const PRESET_DIST = new URL("../packages/preset-standard/dist/preset-standard.js", import.meta.url);
const OUTPUT = new URL("../docs/specs/render-order.md", import.meta.url);

/** Copies `window`'s own globals onto `globalThis`, keeping Node's real `console`. */
function installHeadlessDom() {
  const window = new Window({ url: "http://localhost/" });
  const skip = new Set(["window", "self", "top", "parent", "globalThis", "frames", "console"]);
  for (const key of Object.getOwnPropertyNames(window)) {
    if (skip.has(key)) continue;
    try {
      globalThis[key] = window[key];
    } catch {
      // A handful of happy-dom's own globals are read-only accessors; nothing this script needs.
    }
  }
  globalThis.window = globalThis;
  globalThis.document = window.document;

  // A minimal fake 2D context: any method call is a no-op, any property read/write is stored and
  // echoed back. Good enough for the view/task-bars/tree-grid `setup()` paths this script runs —
  // they call canvas APIs while wiring up layers and an initial paint pass, but this script reads
  // no pixels back out.
  function fakeContext2D() {
    const state = {};
    return new Proxy(state, {
      get(target, prop) {
        if (prop in target) return target[prop];
        if (prop === "measureText") return () => ({ width: 0 });
        if (prop === "getTransform") return () => ({ a: 1, b: 0, c: 0, d: 1, e: 0, f: 0 });
        if (prop === "createLinearGradient" || prop === "createRadialGradient") {
          return () => ({ addColorStop() {} });
        }
        return () => {};
      },
      set(target, prop, value) {
        target[prop] = value;
        return true;
      },
    });
  }
  window.HTMLCanvasElement.prototype.getContext = (type) => (type === "2d" ? fakeContext2D() : null);

  return window;
}

/** `{ key, order, pluginId }[]` -> a Markdown table, ascending by order (already sorted by `orders()`). */
function renderTable(registrations) {
  const header = "| Order | Key | Plugin |\n| ---: | --- | --- |";
  const rows = registrations.map((r) => `| ${r.order} | \`${r.key}\` | \`${r.pluginId}\` |`);
  return [header, ...rows].join("\n");
}

async function main() {
  installHeadlessDom();

  const [{ Gantt }, { presetStandard }] = await Promise.all([
    import(CORE_DIST.href),
    import(PRESET_DIST.href),
  ]);

  const element = document.createElement("div");
  document.body.appendChild(element);
  element.style.width = "800px";
  element.style.height = "600px";

  const host = Gantt.create({ element, plugins: presetStandard() });
  const registrations = host.orders("renderer/layers");
  host.dispose();

  const generatedNote =
    "<!-- Generated by tools/gen-render-order.mjs from a live `host.orders(\"renderer/layers\")`" +
    " snapshot of `presetStandard()` — do not hand-edit; re-run the script instead. -->";

  const scopeNote =
    registrations.length === 0
      ? "\n_No registrations: the composed plugin set contributes no `renderer/layers` entries._\n"
      : `\n${renderTable(registrations)}\n`;

  const body = `# Render order

${generatedNote}

The z-order stack of the canvas drawing passes composed by \`presetStandard()\`
(\`@stargantt/preset-standard\`), read live from \`host.orders("renderer/layers")\`
(docs/specs/architecture.md chapter 1.2 / chapter 7) and sorted ascending by \`order\` — the paint
order the view plugin's renderer draws each pass in, low to high.

This table reflects exactly the officially composed plugins' registered layer orders as of the
last generation run; regenerate with
\`node tools/gen-render-order.mjs\` after \`pnpm run build\` whenever a plugin's registered order
changes.
${scopeNote}
Third-party plugins claim orders in this same registry, on equal terms with official ones
(docs/specs/architecture.md chapter 8) — \`ctx.claimOrder("renderer/layers", key, order)\`.
`;

  await writeFile(OUTPUT, body, "utf8");
  process.stdout.write(`gen-render-order: wrote ${registrations.length} registration(s) to ${OUTPUT.pathname}\n`);
}

await main();
